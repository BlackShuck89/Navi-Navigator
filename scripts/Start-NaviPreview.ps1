# Navi Navigator Firefox-chrome preview. No Firefox installation is altered.
[CmdletBinding()]
param(
    [ValidateSet('modern', 'classic', 'fusion')]
    [string]$Skin = 'modern',

    [string]$ProfileRoot,

    [string]$FirefoxPath,

    [switch]$NoLaunch
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$projectRoot = Split-Path -Parent $PSScriptRoot
$skinRoot = Join-Path $projectRoot 'skins'
$manifestPath = Join-Path $skinRoot 'manifest.json'
$manifest = Get-Content -LiteralPath $manifestPath -Raw | ConvertFrom-Json
$selectedSkin = @($manifest.skins | Where-Object { $_.id -eq $Skin })
if ($selectedSkin.Count -ne 1) {
    throw "Skin '$Skin' is missing or duplicated in skins/manifest.json"
}
$skinFile = Join-Path $skinRoot $selectedSkin[0].css
$baseFile = Join-Path $skinRoot 'base.css'
if (!(Test-Path -LiteralPath $baseFile) -or !(Test-Path -LiteralPath $skinFile)) {
    throw "Skin source missing: $baseFile or $skinFile"
}

if ([string]::IsNullOrWhiteSpace($ProfileRoot)) {
    $localAppData = [Environment]::GetFolderPath('LocalApplicationData')
    if ([string]::IsNullOrWhiteSpace($localAppData)) {
        throw 'Cannot locate LocalApplicationData. Provide -ProfileRoot explicitly.'
    }
    $ProfileRoot = Join-Path $localAppData 'Navi Navigator\PreviewProfiles'
}
$profilePath = Join-Path $ProfileRoot $Skin
$chromePath = Join-Path $profilePath 'chrome'
[void](New-Item -Path $chromePath -ItemType Directory -Force)

$encoding = New-Object System.Text.UTF8Encoding($false)
$css = @(
    '/* Generated by Start-NaviPreview.ps1. Edit skins/*.css instead. */',
    (Get-Content -LiteralPath $baseFile -Raw),
    (Get-Content -LiteralPath $skinFile -Raw)
) -join "`r`n"

[IO.File]::WriteAllText((Join-Path $chromePath 'userChrome.css'), $css, $encoding)

# Dedicated disposable preview profile; user.js is deliberately managed here.
$prefs = @'
user_pref("toolkit.legacyUserProfileCustomizations.stylesheets", true);
user_pref("browser.toolbars.bookmarks.visibility", "always");
user_pref("browser.urlbar.trimURLs", false);
user_pref("browser.tabs.inTitlebar", 0);
user_pref("browser.startup.homepage", "about:home");
'@
[IO.File]::WriteAllText((Join-Path $profilePath 'user.js'), $prefs, $encoding)

Write-Host "Navi $($selectedSkin[0].name) development profile: $profilePath"
if ($NoLaunch) {
    Write-Host 'Profile generated. Firefox was not launched.'
    return
}

if (![string]::IsNullOrWhiteSpace($FirefoxPath)) {
    if (!(Test-Path -LiteralPath $FirefoxPath -PathType Leaf)) {
        throw "Firefox was not found at: $FirefoxPath"
    }
} else {
    $programFilesX86 = [Environment]::GetEnvironmentVariable('ProgramFiles(x86)')
    $searchPaths = @(
        (Join-Path $env:ProgramFiles 'Mozilla Firefox\firefox.exe')
    )
    if (![string]::IsNullOrWhiteSpace($programFilesX86)) {
        $searchPaths += (Join-Path $programFilesX86 'Mozilla Firefox\firefox.exe')
    }
    $installed = @($searchPaths | Where-Object { Test-Path -LiteralPath $_ -PathType Leaf })
    if ($installed.Count -eq 0) {
        throw 'Firefox installation not found. Install Firefox, or supply -FirefoxPath.'
    }
    $FirefoxPath = $installed[0]
}

# -no-remote keeps this instance separate from the user's existing Firefox process.
$arguments = '-no-remote -profile "' + $profilePath + '"'
Start-Process -FilePath $FirefoxPath -ArgumentList $arguments | Out-Null
Write-Host 'Launched an isolated Firefox instance with the Navi development skin.'
